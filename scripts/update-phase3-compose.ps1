$ErrorActionPreference='Stop'
$backendPath=Split-Path $PSScriptRoot -Parent
Push-Location $backendPath
try {
    # Render only variable references; never load the user's real .env or print resolved secrets.
    $rendered=& docker compose --env-file .env.example -f docker-compose.phase3.yml config --no-interpolate --no-path-resolution
    if($LASTEXITCODE -ne 0){throw 'Cannot render the complete Phase 3 configuration.'}
    # Compose config synthesizes project-prefixed resource names. Remove them so -p
    # continues isolating volumes/networks rather than accidentally reusing another project.
    $section=''
    $rendered=@(foreach($line in $rendered){
        if($line -match '^([^\s:]+):'){$section=$matches[1]}
        if($section -in @('volumes','networks') -and $line -match '^    name:'){continue}
        $line
    })
    $header="# Complete Phase 3 default stack. Generated by scripts/update-phase3-compose.ps1.`n# Edit the phase3 overlays, then regenerate. Variables remain unresolved references.`n"
    [IO.File]::WriteAllText((Join-Path $backendPath 'docker-compose.yml'),$header+($rendered -join "`n")+"`n",(New-Object Text.UTF8Encoding($false)))
    & docker compose --env-file .env.example -f docker-compose.yml config --quiet
    if($LASTEXITCODE -ne 0){throw 'Rendered Phase 3 configuration is invalid.'}
    $checkProject='climate-phase3-name-check'
    $isolated=& docker compose --project-name $checkProject --env-file .env.example -f docker-compose.yml config --format json
    if($LASTEXITCODE -ne 0){throw 'Cannot validate project isolation.'}
    $model=($isolated -join "`n")|ConvertFrom-Json
    foreach($group in @($model.volumes,$model.networks)){
        foreach($property in $group.PSObject.Properties){
            if(-not $property.Value.name.StartsWith($checkProject+'_')){throw 'Volume/network name is fixed outside its project.'}
        }
    }
    Write-Output 'Updated the complete default Compose stack without resolving application secrets.'
} finally {Pop-Location}
